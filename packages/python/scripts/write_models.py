"""Writes src/commercebook/models.py, the TypedDicts of the CommerceBook API schemas, from the OpenAPI document with
datamodel-code-generator. The document is docs/openapi.json in the CommerceBook repository (two folders up from this
package) or openapi.json at the root of the public repository; COMMERCEBOOK_OPENAPI names another file.

    python scripts/write_models.py           write src/commercebook/models.py
    python scripts/write_models.py --check   exit 1 when the file differs from a fresh run

Needs datamodel-code-generator (pip install datamodel-code-generator); the published package does not.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
OUT = PKG / "src" / "commercebook" / "models.py"


def source() -> Path:
    for c in (os.environ.get("COMMERCEBOOK_OPENAPI"), PKG / ".." / ".." / "docs" / "openapi.json", PKG / ".." / ".." / "openapi.json"):
        if c and Path(c).exists():
            return Path(c).resolve()
    sys.exit("FAIL python models: no OpenAPI document found")


def generate(doc_path: Path) -> str:
    exe = shutil.which("datamodel-codegen", path=str(Path(sys.executable).parent)) or shutil.which("datamodel-codegen")
    if not exe:
        sys.exit("FAIL python models: datamodel-codegen is not installed (pip install datamodel-code-generator)")
    doc = json.loads(doc_path.read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "models.py"
        subprocess.run(
            [exe, "--input", str(doc_path), "--input-file-type", "openapi", "--output-model-type", "typing.TypedDict",
             "--target-python-version", "3.11", "--disable-timestamp", "--use-field-description",
             "--formatters", "black", "isort", "--output", str(out)],
            check=True, capture_output=True, text=True,
        )
        body = out.read_text(encoding="utf-8")
    # typing.TypedDict carries NotRequired from Python 3.11, so the package needs no typing_extensions.
    body = body.replace("from typing_extensions import TypedDict\n", "from typing import TypedDict\n")
    # closed=True (PEP 728, additionalProperties false) is typing_extensions only; the standard TypedDict refuses it.
    body = body.replace("(TypedDict, closed=True):", "(TypedDict):")
    body = body.replace("from typing import Any, Literal, NotRequired\n\nfrom typing import TypedDict\n", "from typing import Any, Literal, NotRequired, TypedDict\n")
    lines = body.splitlines()
    while lines and (lines[0].startswith("# generated by datamodel-codegen") or lines[0].startswith("#   filename")):
        lines.pop(0)
    title = doc.get("info", {}).get("title", "API")
    version = doc.get("info", {}).get("version", "")
    header = [
        f"# Generated by scripts/write_models.py from the CommerceBook OpenAPI document ({title} {version}, {len(doc.get('paths', {}))} paths)",
        "# with datamodel-code-generator. Do not edit by hand: run python scripts/write_models.py.",
        "# pylint: skip-file",
    ]
    return "\n".join(header + lines).rstrip("\n") + "\n"


def main() -> None:
    doc_path = source()
    fresh = generate(doc_path)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current == fresh:
            print("PASS packages/commercebook-py/src/commercebook/models.py: current")
            return
        print(f"FAIL packages/commercebook-py/src/commercebook/models.py: {'missing' if current is None else 'stale'}; run python scripts/write_models.py")
        sys.exit(1)
    OUT.write_text(fresh, encoding="utf-8")
    print(f"wrote packages/commercebook-py/src/commercebook/models.py ({fresh.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
