// Writes src/schema.ts, the TypeScript types of the CommerceBook API, from the OpenAPI document with
// openapi-typescript. The document is docs/openapi.json in the CommerceBook repository (two folders up from this
// package) or openapi.json at the root of the public repository; COMMERCEBOOK_OPENAPI names another file.
//   node scripts/write-types.mjs           write src/schema.ts
//   node scripts/write-types.mjs --check   exit 1 when src/schema.ts differs from a fresh run (qa:docs runs this)
// Reads files only; no network.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PKG = fileURLToPath(new URL('..', import.meta.url)).replace(/\/$/, '');
const CHECK = process.argv.includes('--check');
const OUT = `${PKG}/src/schema.ts`;
const candidates = [process.env.COMMERCEBOOK_OPENAPI, `${PKG}/../../docs/openapi.json`, `${PKG}/../../openapi.json`].filter(Boolean);
const source = candidates.find((p) => existsSync(p));
if (!source) {
  console.error(`FAIL sdk types: no OpenAPI document (looked at ${candidates.join(', ')})`);
  process.exit(1);
}
let openapiTS;
let astToString;
try {
  ({ default: openapiTS, astToString } = await import(pathToFileURL(`${PKG}/node_modules/openapi-typescript/dist/index.mjs`).href));
} catch {
  console.error(`FAIL sdk types: openapi-typescript is not installed; run npm install in ${PKG}`);
  process.exit(1);
}

const doc = JSON.parse(readFileSync(source, 'utf8'));
const ast = await openapiTS(doc, { alphabetize: false, exportType: false });
const header = [
  '/* eslint-disable */',
  `// Generated by scripts/write-types.mjs from the CommerceBook OpenAPI document (${doc.info?.title ?? 'API'} ${doc.info?.version ?? ''}, ${Object.keys(doc.paths ?? {}).length} paths) with openapi-typescript.`,
  '// Do not edit by hand: run `npm run types` here, or `npm run docs` in the CommerceBook repository.',
  '',
].join('\n');
const fresh = `${header}${astToString(ast)}`.replace(/\n+$/, '\n');

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  if (current === fresh) {
    console.log(`PASS packages/commercebook-sdk/src/schema.ts: current with ${Object.keys(doc.paths).length} paths`);
    process.exit(0);
  }
  console.log(`FAIL packages/commercebook-sdk/src/schema.ts: ${current === null ? 'missing' : 'stale'}; run npm run docs`);
  process.exit(1);
}
writeFileSync(OUT, fresh);
console.log(`wrote packages/commercebook-sdk/src/schema.ts (${Object.keys(doc.paths).length} paths)`);
